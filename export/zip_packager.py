"""ZIP Bundle Packager for Amazon AutoList Studio.

Compiles processed 2000x2000 pure white images, Amazon inventory flat files (.tsv & .csv),
JSON metadata payload, and human-readable listing reports into a downloadable ZIP archive.
"""

import io
import zipfile
import json
from typing import Dict, Any
from PIL import Image

from core.models import CompleteListing
from export.flat_file_generator import AmazonFlatFileGenerator


class ZipBundlePackager:
    """Packages listing assets and metadata into a ready-to-upload ZIP archive."""

    IMAGE_NAMES = {
        1: "MAIN_IMAGE.jpg",
        2: "PT01_ANGLE2.jpg",
        3: "PT02_ANGLE3.jpg",
        4: "PT03_DIMENSIONS.jpg",
        5: "PT04_INUSE.jpg"
    }

    @classmethod
    def create_bundle(
        cls,
        listing: CompleteListing,
        processed_images: Dict[int, Dict[str, Any]]
    ) -> bytes:
        """Builds in-memory zip file containing all assets."""
        zip_buffer = io.BytesIO()

        with zipfile.ZipFile(zip_buffer, "w", zipfile.ZIP_DEFLATED) as zf:
            # 1. Add Processed Images
            for slot_id, filename in cls.IMAGE_NAMES.items():
                img_data = processed_images.get(slot_id)
                if img_data and "image_bytes" in img_data:
                    zf.writestr(f"images/{filename}", img_data["image_bytes"])
                elif img_data and "processed_image" in img_data:
                    buf = io.BytesIO()
                    img_data["processed_image"].save(buf, format="JPEG", quality=95)
                    zf.writestr(f"images/{filename}", buf.getvalue())

            # 2. Add Amazon Inventory Flat Files (TSV & CSV)
            tsv_content = AmazonFlatFileGenerator.generate_tsv(listing)
            zf.writestr("Amazon_Inventory_FlatFile.tsv", tsv_content)

            csv_content = AmazonFlatFileGenerator.generate_csv(listing)
            zf.writestr("Amazon_Inventory_FlatFile.csv", csv_content)

            # 3. Add Raw JSON Listing Payload
            payload_dict = {
                "listing": listing.model_dump(),
                "summary": listing.get_summary_dict(),
                "generator": "Amazon AutoList Studio v1.0.0",
                "brand": listing.identity.brand_name
            }
            zf.writestr("listing_payload.json", json.dumps(payload_dict, indent=2))

            # 4. Add Formatted Markdown / TXT Summary Report
            report_content = cls.generate_summary_report(listing, processed_images)
            zf.writestr("Listing_Summary_Report.md", report_content)

        zip_buffer.seek(0)
        return zip_buffer.getvalue()

    @classmethod
    def generate_summary_report(
        cls,
        listing: CompleteListing,
        processed_images: Dict[int, Dict[str, Any]]
    ) -> str:
        """Generates executive summary report."""
        ident = listing.identity
        desc = listing.description
        det = listing.details
        off = listing.offer
        comp = listing.compliance

        report = f"""# Amazon Product Listing Dossier - {ident.brand_name}
**Generated by Amazon AutoList Studio**

---

### 1. Product Identity
- **Product Title:** {ident.item_name}
- **Brand Name:** {ident.brand_name}
- **Seller SKU:** {off.seller_sku}
- **Product ID / GTIN:** {ident.product_id} ({ident.product_id_type})
- **Item Type Keyword:** {ident.item_type_keyword}
- **Model Name / Number:** {ident.model_name} / {ident.model_number}

---

### 2. Pricing & Inventory (Offer)
- **Standard Selling Price:** ₹{off.standard_price:,.2f}
- **Maximum Retail Price (MRP):** ₹{off.list_price:,.2f}
- **Seller Discount:** {off.discount_percent}% OFF
- **Initial Inventory Stock:** {off.quantity} units
- **Fulfillment Channel:** {off.fulfillment_channel}
- **Order Handling Time:** {off.handling_time} day(s)
- **Item Condition:** {off.condition_type}

---

### 3. Key Product Features (5 Bullet Points)
1. **{desc.bullet_point_1}**
2. **{desc.bullet_point_2}**
3. **{desc.bullet_point_3}**
4. **{desc.bullet_point_4}**
5. **{desc.bullet_point_5}**

---

### 4. Product Details & Specifications
- **Material:** {det.material}
- **Color & Finish:** {det.color} ({det.finish_type})
- **Shape & Style:** {det.item_shape}
- **Capacity:** {det.capacity}
- **Item Weight:** {det.item_weight}
- **Package Dimensions:** {det.package_dimensions}
- **Care Instructions:** {det.care_instructions}
- **Dishwasher Safe:** {"Yes" if det.is_dishwasher_safe else "No"}
- **Induction Compatible:** {"Yes" if det.is_induction_compatible else "No"}

---

### 5. Safety, Taxation & Compliance
- **Country of Origin:** {comp.country_of_origin}
- **HSN Code:** {comp.hsn_code}
- **Product GST Tax Code:** {comp.gst_tax_code}
- **Manufacturer:** {comp.manufacturer}
- **Packer Information:** {comp.packer_details}
- **Warranty:** {comp.warranty_description}
- **Certifications:** {comp.compliance_certification}

---

### 6. Backend Search Terms (Generic Keywords)
`{desc.search_terms}`
*(Character Length: {len(desc.search_terms)} bytes - Amazon Limit: 249 bytes)*

---

### 7. Processed Image Inspection & Amazon Compliance
"""
        for slot_id, fname in cls.IMAGE_NAMES.items():
            slot_info = processed_images.get(slot_id, {})
            comp_info = slot_info.get("compliance", {})
            status = "PASSED (2000x2000px, Pure White #FFFFFF)" if comp_info.get("is_compliant") else "Ready"
            dims = slot_info.get("final_dimensions", (2000, 2000))
            report += f"- **Slot {slot_id} ({fname}):** Dimensions: {dims[0]}x{dims[1]}px | Status: {status}\n"

        return report
